-- Genesis campaign ledger. Apply to a dedicated PostgreSQL database with a
-- migration role; never expose these tables to browser clients or webhooks.
-- This migration creates no campaign, rewards, or public API.
BEGIN;

CREATE SCHEMA genesis;

CREATE TABLE genesis.campaigns (
    id text PRIMARY KEY,
    cluster text NOT NULL CHECK (cluster IN ('localnet', 'devnet', 'testnet', 'mainnet-beta')),
    status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'active', 'closed', 'review', 'finalized')),
    starts_at timestamptz,
    ends_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (id, cluster),
    CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at),
    CHECK (status = 'draft' OR (starts_at IS NOT NULL AND ends_at IS NOT NULL))
);

-- Published revisions are append-only. The rules JSON is validated by the
-- application against a versioned schema before publication.
CREATE TABLE genesis.rule_revisions (
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    revision integer NOT NULL CHECK (revision > 0),
    effective_from timestamptz NOT NULL,
    rules jsonb NOT NULL CHECK (jsonb_typeof(rules) = 'object'),
    published_by text NOT NULL,
    published_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, revision),
    UNIQUE (campaign_id, effective_from)
);

-- Cursors advance only after a whole slot range has been decoded, checked
-- against finalized RPC data, and committed together with its events.
CREATE TABLE genesis.indexer_cursors (
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    program_id text NOT NULL,
    decoder_version text NOT NULL,
    next_slot bigint NOT NULL CHECK (next_slot >= 0),
    reconciled_through_slot bigint CHECK (reconciled_through_slot >= 0),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, program_id, decoder_version)
);

-- An event ordinal is deterministic within its outer transaction instruction.
-- The same signature/instruction/ordinal must always decode to identical data.
CREATE TABLE genesis.chain_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    cluster text NOT NULL CHECK (cluster IN ('localnet', 'devnet', 'testnet', 'mainnet-beta')),
    signature text NOT NULL,
    instruction_index integer NOT NULL CHECK (instruction_index >= 0),
    event_index integer NOT NULL CHECK (event_index >= 0),
    event_kind text NOT NULL CHECK (event_kind IN
        ('swap', 'position_open', 'liquidity_increase', 'liquidity_decrease', 'position_close')),
    slot bigint NOT NULL CHECK (slot >= 0),
    block_time timestamptz NOT NULL,
    wallet text NOT NULL,
    pool_address text,
    position_address text,
    payload jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    event_sha256 text NOT NULL CHECK (event_sha256 ~ '^[0-9a-f]{64}$'),
    decoder_version text NOT NULL,
    verified_at timestamptz NOT NULL,
    ingested_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (campaign_id, id),
    UNIQUE (campaign_id, cluster, signature, instruction_index, event_index),
    FOREIGN KEY (campaign_id, cluster) REFERENCES genesis.campaigns(id, cluster)
);

CREATE INDEX chain_events_wallet_time_idx
    ON genesis.chain_events (campaign_id, wallet, block_time, id);
CREATE INDEX chain_events_slot_idx
    ON genesis.chain_events (campaign_id, slot, id);
CREATE INDEX chain_events_position_idx
    ON genesis.chain_events (campaign_id, position_address, slot)
    WHERE position_address IS NOT NULL;

-- A conflicting replay is quarantined for investigation, never overwritten.
CREATE TABLE genesis.ingest_conflicts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    existing_event_id bigint NOT NULL REFERENCES genesis.chain_events(id),
    observed_event_sha256 text NOT NULL
        CHECK (observed_event_sha256 ~ '^[0-9a-f]{64}$'),
    observed_decoder_version text NOT NULL,
    observed_at timestamptz NOT NULL DEFAULT now(),
    resolution text NOT NULL DEFAULT 'open'
        CHECK (resolution IN ('open', 'decoder_fixed', 'source_error', 'ignored')),
    resolved_at timestamptz,
    notes text,
    UNIQUE (existing_event_id, observed_event_sha256, observed_decoder_version)
);

-- This is a value-after-event snapshot, not an on-chain claim. The source
-- records must cover every size and valuation change used for time weighting.
CREATE TABLE genesis.lp_value_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    snapshot_key text NOT NULL,
    position_address text NOT NULL,
    wallet text NOT NULL,
    pool_address text NOT NULL,
    effective_at timestamptz NOT NULL,
    sequence bigint NOT NULL CHECK (sequence >= 0),
    value_usd_cents numeric(38, 0) NOT NULL CHECK (value_usd_cents >= 0),
    chain_event_id bigint REFERENCES genesis.chain_events(id),
    valuation_source text NOT NULL,
    valuation_version text NOT NULL,
    price_evidence jsonb NOT NULL CHECK (jsonb_typeof(price_evidence) = 'object'),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (campaign_id, snapshot_key),
    UNIQUE (campaign_id, position_address, effective_at, sequence),
    FOREIGN KEY (campaign_id, chain_event_id)
        REFERENCES genesis.chain_events(campaign_id, id)
);

CREATE INDEX lp_value_snapshots_wallet_time_idx
    ON genesis.lp_value_snapshots (campaign_id, wallet, effective_at);

-- Rebuildable projection. Never use it as the only record of campaign credit.
CREATE TABLE genesis.wallet_progress (
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    wallet text NOT NULL,
    rule_revision integer NOT NULL,
    projection_version text NOT NULL,
    computed_through_slot bigint NOT NULL CHECK (computed_through_slot >= 0),
    qualifying_swaps integer NOT NULL DEFAULT 0 CHECK (qualifying_swaps >= 0),
    active_trading_days integer NOT NULL DEFAULT 0 CHECK (active_trading_days >= 0),
    lp_usd_cent_seconds numeric(38, 0) NOT NULL DEFAULT 0
        CHECK (lp_usd_cent_seconds >= 0),
    provisional_xp bigint NOT NULL DEFAULT 0 CHECK (provisional_xp >= 0),
    computed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, wallet),
    FOREIGN KEY (campaign_id, rule_revision)
        REFERENCES genesis.rule_revisions(campaign_id, revision)
);

CREATE TABLE genesis.quest_definitions (
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    slug text NOT NULL,
    category text NOT NULL CHECK (category IN
        ('Featured', 'Trading', 'Liquidity', 'Community', 'Referral')),
    title text NOT NULL,
    description text NOT NULL,
    verification text NOT NULL CHECK (verification IN ('indexed', 'derived', 'manual')),
    enabled boolean NOT NULL DEFAULT false,
    rules jsonb NOT NULL CHECK (jsonb_typeof(rules) = 'object'),
    PRIMARY KEY (campaign_id, slug)
);

CREATE TABLE genesis.quest_progress (
    campaign_id text NOT NULL,
    wallet text NOT NULL,
    quest_slug text NOT NULL,
    progress_value numeric(38, 0) NOT NULL DEFAULT 0 CHECK (progress_value >= 0),
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'in_progress', 'provisional', 'approved', 'rejected')),
    provisional_xp bigint NOT NULL DEFAULT 0 CHECK (provisional_xp >= 0),
    computed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, wallet, quest_slug),
    FOREIGN KEY (campaign_id, wallet)
        REFERENCES genesis.wallet_progress(campaign_id, wallet),
    FOREIGN KEY (campaign_id, quest_slug)
        REFERENCES genesis.quest_definitions(campaign_id, slug)
);

-- One attribution per referee and campaign. Connection/click is not credit.
CREATE TABLE genesis.referrals (
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    referee_wallet text NOT NULL,
    referrer_wallet text NOT NULL,
    attributed_at timestamptz NOT NULL DEFAULT now(),
    attribution_source text NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'qualified', 'rejected')),
    qualified_at timestamptz,
    PRIMARY KEY (campaign_id, referee_wallet),
    CHECK (referee_wallet <> referrer_wallet),
    CHECK ((status = 'qualified') = (qualified_at IS NOT NULL))
);

-- Review state is separate from rebuildable progress. Actions are append-only.
CREATE TABLE genesis.wallet_reviews (
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    wallet text NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'flagged', 'disqualified')),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (campaign_id, wallet)
);

CREATE TABLE genesis.review_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    wallet text NOT NULL,
    admin_wallet text NOT NULL,
    action text NOT NULL CHECK (action IN ('approve', 'flag', 'disqualify', 'restore')),
    previous_status text NOT NULL,
    new_status text NOT NULL,
    reason text NOT NULL CHECK (length(trim(reason)) > 0),
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX review_actions_wallet_idx
    ON genesis.review_actions (campaign_id, wallet, created_at);

-- These rows represent accounting only; this migration creates no payout path.
CREATE TABLE genesis.reward_epochs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id text NOT NULL REFERENCES genesis.campaigns(id),
    epoch_number integer NOT NULL CHECK (epoch_number >= 0),
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    rule_revision integer NOT NULL,
    computed_through_slot bigint CHECK (computed_through_slot >= 0),
    status text NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'calculated', 'review', 'approved', 'finalized')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (campaign_id, epoch_number),
    CHECK (ends_at > starts_at),
    FOREIGN KEY (campaign_id, rule_revision)
        REFERENCES genesis.rule_revisions(campaign_id, revision)
);

CREATE TABLE genesis.reward_allocations (
    epoch_id bigint NOT NULL REFERENCES genesis.reward_epochs(id),
    wallet text NOT NULL,
    provisional_solv3_raw numeric(38, 0) NOT NULL DEFAULT 0
        CHECK (provisional_solv3_raw >= 0),
    approved_solv3_raw numeric(38, 0) CHECK (approved_solv3_raw >= 0),
    status text NOT NULL DEFAULT 'provisional'
        CHECK (status IN ('provisional', 'review', 'approved', 'disqualified')),
    calculated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (epoch_id, wallet),
    CHECK (status <> 'approved' OR approved_solv3_raw IS NOT NULL)
);

CREATE FUNCTION genesis.reject_immutable_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Genesis ledger rows are append-only';
END;
$$;

CREATE TRIGGER rule_revisions_immutable BEFORE UPDATE OR DELETE
    ON genesis.rule_revisions FOR EACH ROW
    EXECUTE FUNCTION genesis.reject_immutable_change();
CREATE TRIGGER chain_events_immutable BEFORE UPDATE OR DELETE
    ON genesis.chain_events FOR EACH ROW
    EXECUTE FUNCTION genesis.reject_immutable_change();
CREATE TRIGGER review_actions_immutable BEFORE UPDATE OR DELETE
    ON genesis.review_actions FOR EACH ROW
    EXECUTE FUNCTION genesis.reject_immutable_change();

COMMIT;
